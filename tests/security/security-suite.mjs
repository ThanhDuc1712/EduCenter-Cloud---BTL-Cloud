#!/usr/bin/env node
/**
 * EduCenter Cloud — black-box security suite (tester: Dương). Complements tests/security/authz/.
 * Runs against a RUNNING deployment: local (start-local.ps1) or Azure.
 *
 *   $env:BASE_URL = "http://localhost:3000"      # or https://<app>.azurewebsites.net
 *   $env:TEST_PASSWORD = "<seed password>"       # local default: Demo@12345 (README)
 *   node tests/security/security-suite.mjs
 *
 * Results: PASS / FAIL / INFO (needs a decision, not a verdict) / SKIP (not applicable here).
 * Checks marked localOnly send requests that WOULD change data if the API were broken; they are
 * skipped automatically when BASE_URL is not localhost.
 * Writes <OUT_DIR>/security-<timestamp>.csv and .md (default OUT_DIR: ../EduCenter-test-results,
 * outside the repo). Nothing secret (cookies, tokens, passwords, response bodies) is written.
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { execSync } from 'node:child_process';
import { API, APP_ORIGIN, BASE_URL, IS_LOCAL, Session, TENANT_A, TENANT_B, TEST_PASSWORD, cookieAttributes, itemsOf, uuidsIn } from './lib/client.mjs';

if (!TEST_PASSWORD) {
  console.error('TEST_PASSWORD is required for a non-local BASE_URL.');
  process.exit(2);
}

const results = [];
function record(id, title, severity, expected, actual, result, note = '') {
  results.push({ id, title, severity, expected, actual, result, note });
  const tag = { PASS: 'PASS', FAIL: 'FAIL', INFO: 'INFO', SKIP: 'SKIP' }[result];
  console.log(`${tag.padEnd(4)}  ${id.padEnd(7)} ${title}${actual ? `  — ${actual}` : ''}${note ? `  (${note})` : ''}`);
}
const pass = (c) => (c ? 'PASS' : 'FAIL');
const looksLikeStack = (text) => /\bat .+\(.+:\d+:\d+\)|\.ts:\d+|node_modules|PrismaClient|SELECT .+ FROM/i.test(text ?? '');

let sha = 'unknown';
try {
  sha = execSync('git rev-parse --short HEAD', { stdio: ['ignore', 'pipe', 'ignore'] }).toString().trim();
} catch {}

console.log(`EduCenter security suite → ${API}  (origin ${APP_ORIGIN}, ${IS_LOCAL ? 'LOCAL' : 'REMOTE'}, sha ${sha})\n`);

// ---------------------------------------------------------------- setup: actors
const anon = new Session('anonymous');
const adminA = new Session('adminA');
const adminB = new Session('adminB');

const health = await anon.call('GET', '/health');
if (health.status !== 200) {
  console.error(`API not reachable at ${API}/health (status ${health.status} ${health.error ?? ''}). Start it first.`);
  process.exit(2);
}

const loginA = await adminA.login(TENANT_A, `admin@${TENANT_A}.edu.example`);
const loginB = await adminB.login(TENANT_B, `admin@${TENANT_B}.edu.example`);
if (loginA.status !== 200 || loginB.status !== 200) {
  console.error(`Admin login failed (A=${loginA.status}, B=${loginB.status}). Check TEST_PASSWORD / seed data.`);
  process.exit(2);
}

const activeStudents = itemsOf(await adminA.call('GET', '/students?status=ACTIVE&pageSize=50')).filter((s) => s.email);
const inactiveStudents = itemsOf(await adminA.call('GET', '/students?status=INACTIVE&pageSize=10')).filter((s) => s.email);
const teachersA = itemsOf(await adminA.call('GET', '/teachers?pageSize=50')).filter((t) => t.email);
const studentA = activeStudents[0];
const teacherA = teachersA[0];

const student = new Session('student');
const teacher = new Session('teacher');
if (studentA) await student.login(TENANT_A, studentA.email);
if (teacherA) await teacher.login(TENANT_A, teacherA.email);

// ---------------------------------------------------------------- 1. platform basics
record('SEC-01', 'Health is public and leaks no secrets', 'High', '200, no connection string/password', `${health.status}`,
  pass(health.status === 200 && !/postgres(ql)?:\/\/|password|secret/i.test(health.text)));

const h = health.headers;
const missing = [];
if (h.get('x-powered-by')) missing.push('x-powered-by present');
if ((h.get('x-content-type-options') ?? '').toLowerCase() !== 'nosniff') missing.push('nosniff missing');
if (!h.get('content-security-policy')) missing.push('CSP missing');
if (!h.get('x-request-id')) missing.push('X-Request-ID missing');
if (!IS_LOCAL && !h.get('strict-transport-security')) missing.push('HSTS missing');
record('SEC-02', 'Security headers on API responses', 'Medium', 'no x-powered-by; nosniff; CSP; X-Request-ID (+HSTS remote)',
  missing.length ? missing.join(', ') : 'all present', pass(missing.length === 0));

const spoof = await anon.call('GET', '/health', { headers: { 'x-request-id': 'attacker-chosen-id' } });
record('SEC-03', 'X-Request-ID is generated by the server', 'Low', 'response id ≠ client value',
  spoof.headers.get('x-request-id') === 'attacker-chosen-id' ? 'echoed client value' : 'server-generated',
  pass(spoof.headers.get('x-request-id') !== 'attacker-chosen-id'));

const nf = await adminA.call('GET', '/khong-ton-tai-xyz');
record('SEC-04', 'Unknown route: standard error body, no stack trace', 'Medium', '404 {code,message,requestId}, no stack',
  `${nf.status}, code=${nf.json?.code ?? '-'}`,
  pass(nf.status === 404 && nf.json?.code && nf.json?.requestId && !looksLikeStack(nf.text)));

const noAuth = await anon.call('GET', '/students');
record('SEC-05', 'Protected route without login', 'Critical', '401, no data', `${noAuth.status}`,
  pass(noAuth.status === 401 && itemsOf(noAuth).length === 0));

// ---------------------------------------------------------------- 2. authentication
const probe = new Session('probe');
if (studentA) {
  const wrongPw = await probe.call('POST', '/auth/login', { body: { tenantSlug: TENANT_A, email: studentA.email, password: 'Wrong-password-1!' } });
  const unknown = await probe.call('POST', '/auth/login', { body: { tenantSlug: TENANT_A, email: `no-such-user-${Date.now()}@${TENANT_A}.edu.example`, password: 'Wrong-password-1!' } });
  const wrongTenant = await probe.call('POST', '/auth/login', { body: { tenantSlug: TENANT_B, email: studentA.email, password: TEST_PASSWORD } });
  const same = wrongPw.status === unknown.status && unknown.status === wrongTenant.status && wrongPw.json?.message === unknown.json?.message && unknown.json?.message === wrongTenant.json?.message;
  record('SEC-10', 'Login errors do not reveal which part is wrong', 'Medium', 'same 401 + same message (wrong pw / unknown email / wrong center)',
    `${wrongPw.status}/${unknown.status}/${wrongTenant.status}`, pass(same && wrongPw.status === 401));
  // a successful login resets the account counter used above
  await new Session('reset').login(TENANT_A, studentA.email);
} else record('SEC-10', 'Login error messages', 'Medium', '', 'no active student with email', 'SKIP');

{
  // ST10: brute force on ONE account key (a non-existent email, so no real user is locked).
  const victim = `bruteforce-${Date.now()}@${TENANT_A}.edu.example`;
  const statuses = [];
  let last;
  for (let i = 0; i < 6; i++) {
    last = await probe.call('POST', '/auth/login', { body: { tenantSlug: TENANT_A, email: victim, password: `Wrong-${i}` } });
    statuses.push(last.status);
  }
  const retryAfter = last.headers.get('retry-after');
  record('SEC-11', 'ST10 brute force: account locked after 5 failures', 'High', 'attempts 1-5 → 401, 6th → 429 + Retry-After',
    `${statuses.join(',')} retry-after=${retryAfter ?? '-'}`, pass(statuses.slice(0, 5).every((s) => s === 401) && statuses[5] === 429 && Number(retryAfter) > 0));
}

{
  const attrs = cookieAttributes(loginA.setCookies);
  const ok = attrs && attrs.httpOnly && attrs.sameSite === 'lax' && (IS_LOCAL || (attrs.secure && attrs.name.startsWith('__Host-')));
  record('SEC-12', 'Session cookie flags', 'High', IS_LOCAL ? 'HttpOnly + SameSite=Lax' : 'HttpOnly + SameSite=Lax + Secure + __Host- prefix',
    attrs ? `${attrs.name}: httpOnly=${attrs.httpOnly} secure=${attrs.secure} sameSite=${attrs.sameSite}` : 'no session cookie', pass(!!ok));
}

{
  const s = new Session('logout-check');
  const li = studentA ? await s.login(TENANT_A, studentA.email) : { status: 0 };
  const stolen = s.cookie;
  await s.logout();
  const replay = new Session('replay');
  replay.cookie = stolen;
  const r = await replay.call('GET', '/context');
  record('SEC-13', 'Logout revokes the session on the server', 'High', 'old cookie → 401 after logout', `login=${li.status} replay=${r.status}`,
    li.status === 200 ? pass(r.status === 401) : 'SKIP');
}

if (inactiveStudents[0]) {
  const r = await new Session('inactive').login(TENANT_A, inactiveStudents[0].email);
  record('SEC-14', 'INACTIVE student login (decision needed)', 'Medium', 'CHỜ DEV: INACTIVE có được đăng nhập không?', `${r.status}`, 'INFO',
    r.status === 200 ? 'currently ALLOWED — code blocks only ARCHIVED (session.service.ts)' : 'currently blocked');
} else record('SEC-14', 'INACTIVE student login', 'Medium', '', 'no INACTIVE student', 'SKIP');

{
  const r = await anon.call('POST', '/auth/change-password', { body: { currentPassword: 'x', newPassword: 'Another-pass-123!' } });
  record('SEC-15', 'change-password requires a session', 'High', '401', `${r.status}`, pass(r.status === 401));
}

{
  const opt = await anon.call('GET', '/auth/options');
  const enabled = opt.json?.registrationEnabled === true;
  record('SEC-16', 'Public self-registration on this environment', 'Medium', IS_LOCAL ? 'informational locally' : 'disabled on the graded demo (decision needed)',
    `registrationEnabled=${opt.json?.registrationEnabled}`, IS_LOCAL ? 'INFO' : enabled ? 'INFO' : 'PASS',
    !IS_LOCAL && enabled ? 'anyone can create STUDENT accounts in the demo centers — ask Đức' : '');
}

if (!IS_LOCAL) {
  const r = await new Session('default-pw').login(TENANT_A, `admin@${TENANT_A}.edu.example`, 'Demo@12345');
  record('SEC-17', 'Demo admin does NOT use the public default password', 'Critical', 'login with README password rejected', `${r.status}`, pass(r.status !== 200));
} else record('SEC-17', 'Default password on cloud demo', 'Critical', '', 'local run', 'SKIP', 'run against Azure');

// ---------------------------------------------------------------- 3. CSRF / origin
{
  const r = await adminA.call('POST', '/notifications/read-all', { origin: 'https://evil.example' });
  record('SEC-20', 'Cross-origin write rejected (CSRF)', 'High', '403', `${r.status}`, pass(r.status === 403));
  const r2 = await adminA.call('POST', '/notifications/read-all', { origin: null });
  record('SEC-21', 'Write without Origin header (decision needed)', 'Low', 'CHỜ DEV: có bắt buộc Origin không?', `${r2.status}`, 'INFO',
    r2.status < 300 ? 'accepted — protection relies on SameSite=Lax cookie' : 'rejected');
}

// ---------------------------------------------------------------- 4. role & tenant isolation spot checks
const ops = [
  ['GET', '/cloud/overview'], ['GET', '/cloud/logs'], ['POST', '/cloud/reconciler/run'], ['GET', '/activity'], ['GET', '/reports/students'],
];
for (const [actor, s] of [['teacher', teacher], ['student', student]]) {
  if (!s.cookie) {
    record(`SEC-3${actor === 'teacher' ? 0 : 1}`, `Admin-only routes as ${actor}`, 'Critical', '', `no ${actor} session`, 'SKIP');
    continue;
  }
  const bad = [];
  for (const [m, p] of ops) {
    const r = await s.call(m, p);
    if (r.status !== 403 && r.status !== 404) bad.push(`${m} ${p}=${r.status}`);
  }
  record(`SEC-3${actor === 'teacher' ? 0 : 1}`, `Admin-only routes (/cloud, /activity, /reports) as ${actor}`, 'Critical', '403/404 for all',
    bad.length ? bad.join('; ') : `${ops.length}/${ops.length} denied`, pass(bad.length === 0));
}
if (teacher.cookie) {
  const r = await teacher.call('GET', '/invoices');
  record('SEC-32', 'Teacher cannot read tuition', 'High', '403', `${r.status}`, pass(r.status === 403));
}

{
  // Every id adminA can see must be invisible to adminB.
  const studentsA = itemsOf(await adminA.call('GET', '/students?pageSize=5'));
  const classesA = itemsOf(await adminA.call('GET', '/classrooms?pageSize=5'));
  const invoicesA = itemsOf(await adminA.call('GET', '/invoices?pageSize=5'));
  const probes = [
    ...studentsA.slice(0, 2).map((x) => `/students/${x.id}`),
    ...classesA.slice(0, 2).map((x) => `/classrooms/${x.id}`),
    ...invoicesA.slice(0, 2).map((x) => `/invoices/${x.id}`),
    ...studentsA.slice(0, 1).map((x) => `/students/${x.id}/grades`),
  ];
  const leaks = [];
  for (const p of probes) {
    const r = await adminB.call('GET', p);
    if (r.status === 200) leaks.push(p.replace(/[0-9a-f-]{36}/, ':id'));
  }
  record('SEC-33', 'Admin of center B reading center A records by id', 'Critical', '404 for all', leaks.length ? `LEAK: ${leaks.join(', ')}` : `${probes.length}/${probes.length} denied`,
    probes.length ? pass(leaks.length === 0) : 'SKIP');
}

{
  // BUG-02 regression: /cloud/logs must not show another center's material ids.
  const matsA = new Set(itemsOf(await adminA.call('GET', '/materials?pageSize=100')).map((m) => String(m.id).toLowerCase()));
  const logsB = await adminB.call('GET', '/cloud/logs?pageSize=100');
  const leaked = [...uuidsIn(logsB.json?.items ?? [])].filter((id) => matsA.has(id));
  record('SEC-34', 'BUG-02: /cloud/logs isolates tenants', 'High', 'no center-A material id in center-B logs',
    logsB.status === 200 ? `${leaked.length} leaked id(s)` : `status ${logsB.status}`,
    logsB.status === 200 ? pass(leaked.length === 0) : 'INFO', logsB.status === 403 && !IS_LOCAL ? 'ops API blocked by OPS_ALLOWED_CIDRS' : '');
}

if (studentA) {
  const r = await student.call('GET', '/students?pageSize=100');
  const ids = itemsOf(r).map((x) => x.id);
  record('SEC-35', 'Student list shows only the student', 'High', '0 or 1 item (self)', `${r.status}, ${ids.length} item(s)`,
    pass(r.status === 403 || ids.every((id) => id === studentA.id)));
}

// ---------------------------------------------------------------- 5. input validation (local only: rejected writes)
{
  const inv = itemsOf(await adminA.call('GET', '/invoices?pageSize=20')).find((i) => i.status !== 'PAID' && i.status !== 'CANCELLED');
  if (!IS_LOCAL) record('SEC-40', 'Payment amount validation', 'High', '', 'remote run', 'SKIP', 'write test — local only');
  else if (!inv) record('SEC-40', 'Payment amount validation', 'High', '', 'no open invoice', 'SKIP');
  else {
    const bad = [];
    let i = 0;
    for (const amountVnd of ['-1', '1.5', 'abc', '0']) {
      // valid Idempotency-Key so a 400 can only come from the amount itself
      const r = await adminA.call('POST', `/invoices/${inv.id}/payments`, { body: { amountVnd, method: 'CASH' }, headers: { 'idempotency-key': `qa${Date.now()}x${i++}` } });
      const aboutAmount = JSON.stringify(r.json ?? {}).includes('amountVnd');
      if (r.status !== 400 || !aboutAmount) bad.push(`${amountVnd}→${r.status}${aboutAmount ? '' : ' (not an amount error)'}`);
    }
    record('SEC-40', 'Payment rejects negative / decimal / text / zero', 'High', '400 ×4', bad.length ? bad.join(', ') : '400 ×4', pass(bad.length === 0));
  }
}

if (IS_LOCAL && studentA) {
  const r = await adminA.call('PATCH', `/students/${studentA.id}`, { body: { tenantId: '00000000-0000-0000-0000-000000000000', role: 'ADMIN' } });
  record('SEC-41', 'tenantId / role in request body rejected', 'Critical', '400', `${r.status}`, pass(r.status === 400));
} else record('SEC-41', 'tenantId/role in body', 'Critical', '', IS_LOCAL ? 'no student' : 'remote run', 'SKIP');

{
  const r = await adminA.call('GET', '/students?pageSize=1000');
  record('SEC-42', 'Page size above 100 rejected', 'Low', '400', `${r.status}`, pass(r.status === 400));
  const bad = [];
  for (const q of ["' OR 1=1 --", '%', '"; DROP TABLE students; --', '\\x00']) {
    const s = await adminA.call('GET', `/students?q=${encodeURIComponent(q)}`);
    if (s.status >= 500 || looksLikeStack(s.text)) bad.push(`${JSON.stringify(q)}→${s.status}`);
  }
  record('SEC-43', 'ST08 SQL-injection style search input', 'High', 'never 5xx / never DB error text', bad.length ? bad.join(', ') : 'all handled', pass(bad.length === 0));
}

{
  const big = JSON.stringify({ tenantSlug: TENANT_A, email: 'a@b.c', password: 'x'.repeat(1_200_000) });
  const r = await anon.call('POST', '/auth/login', { rawBody: big });
  record('SEC-44', 'Oversized JSON body rejected', 'Medium', '413', `${r.status}`, pass(r.status === 413));
}

// ---------------------------------------------------------------- 6. storage & callback
{
  const a = await anon.call('GET', '/storage/local/object');
  const b = await anon.call('GET', '/storage/local/object?token=forged.token.value');
  const ok = [403, 404].includes(a.status) && [403, 404].includes(b.status);
  record('SEC-50', 'Local storage download needs a valid signed token', 'High', '403 (404 when OSS mode)', `${a.status}/${b.status}`, pass(ok));
}
{
  const r = await anon.call('POST', '/internal/material-callback', { rawBody: JSON.stringify({ materialId: '00000000-0000-0000-0000-000000000000', status: 'READY' }), origin: null });
  record('SEC-51', 'ST11 forged FC callback (no HMAC) rejected', 'Critical', '401', `${r.status}`, pass(r.status === 401));
}

// ---------------------------------------------------------------- report
const counts = results.reduce((a, r) => ((a[r.result] = (a[r.result] ?? 0) + 1), a), {});
console.log(`\nPASS ${counts.PASS ?? 0}  FAIL ${counts.FAIL ?? 0}  INFO ${counts.INFO ?? 0}  SKIP ${counts.SKIP ?? 0}`);

const outDir = resolve(process.env.OUT_DIR ?? '../EduCenter-test-results');
mkdirSync(outDir, { recursive: true });
const stamp = new Date().toISOString().replace(/[:.]/g, '-').slice(0, 19);
const esc = (v) => `"${String(v ?? '').replace(/"/g, '""')}"`;
const meta = { date: new Date().toISOString(), sha, target: BASE_URL, mode: IS_LOCAL ? 'LOCAL' : 'REMOTE' };
writeFileSync(resolve(outDir, `security-${stamp}.csv`), '﻿' + ['id,title,severity,expected,actual,result,note,sha,target,date', ...results.map((r) => [r.id, r.title, r.severity, r.expected, r.actual, r.result, r.note, meta.sha, meta.target, meta.date].map(esc).join(','))].join('\n'));
writeFileSync(resolve(outDir, `security-${stamp}.md`), [
  `# Security suite — ${meta.mode}`,
  '',
  `Target \`${meta.target}\` · commit \`${meta.sha}\` · ${meta.date}`,
  '',
  `**PASS ${counts.PASS ?? 0} · FAIL ${counts.FAIL ?? 0} · INFO ${counts.INFO ?? 0} · SKIP ${counts.SKIP ?? 0}**`,
  '',
  '| ID | Check | Severity | Expected | Actual | Result | Note |',
  '|---|---|---|---|---|---|---|',
  ...results.map((r) => `| ${r.id} | ${r.title} | ${r.severity} | ${r.expected} | ${r.actual} | **${r.result}** | ${r.note} |`),
  '',
].join('\n'));
console.log(`Saved: ${resolve(outDir, `security-${stamp}.csv`)} (+ .md)`);
process.exit(counts.FAIL ? 1 : 0);
